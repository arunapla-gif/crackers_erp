import 'dart:async';
import 'dart:convert';
import 'dart:js_interop';
import 'dart:js_interop_unsafe';

import 'package:http/http.dart' as http;

import '../../core/config/app_config.dart';
import '../../domain/models/app_update_info.dart';
import 'app_updater_service.dart';

AppUpdaterService createNativeAppUpdaterService() => WebAppUpdaterService();

@JS('window')
external JSObject get _jsWindow;

@JS('navigator')
external JSObject? get _jsNavigator;

class WebAppUpdaterService implements AppUpdaterService {
  WebAppUpdaterService({http.Client? client}) : _client = client;

  final http.Client? _client;

  @override
  bool get isSupportedPlatform => true;

  @override
  bool get isWebReloadUpdater => true;

  @override
  Future<AppVersionInfo?> getInstalledVersion() async {
    return const AppVersionInfo(
      versionCode: AppConfig.appVersionCode,
      versionName: AppConfig.appVersionName,
    );
  }

  @override
  Future<AppUpdateInfo?> checkForUpdate(String apiBaseUrl) async {
    final httpClient = _client ?? http.Client();
    final ts = DateTime.now().millisecondsSinceEpoch;

    int? webCode;
    String? webName;

    try {
      // /version.json is generated by `flutter build web` and served no-store.
      final versionJsonUri = Uri.base.resolve('/version.json?ts=$ts');
      final res = await httpClient
          .get(
            versionJsonUri,
            headers: const {
              'Accept': 'application/json',
              'Cache-Control': 'no-cache',
            },
          )
          .timeout(const Duration(seconds: 10));
      if (res.statusCode >= 200 && res.statusCode < 300) {
        final decoded = jsonDecode(res.body);
        if (decoded is Map<String, dynamic>) {
          final parsedCode =
              int.tryParse('${decoded['build_number'] ?? ''}'.trim());
          final parsedName = '${decoded['version'] ?? ''}'.trim();
          if (parsedCode != null && parsedCode > 0) {
            webCode = parsedCode;
            webName = parsedName.isNotEmpty ? parsedName : '1.0.0';
          }
        }
      }
    } catch (_) {
      // Fallback to /api/app/version below
    }

    AppUpdateInfo? apiMeta;
    try {
      final apiUri = buildVersionCheckUri(apiBaseUrl).replace(
        queryParameters: {'ts': '$ts'},
      );
      final res = await httpClient
          .get(
            apiUri,
            headers: const {
              'Accept': 'application/json',
              'Cache-Control': 'no-cache',
            },
          )
          .timeout(const Duration(seconds: 10));
      if (res.statusCode >= 200 && res.statusCode < 300) {
        final decoded = jsonDecode(res.body);
        if (decoded is Map<String, dynamic>) {
          apiMeta = AppUpdateInfo.fromJson(decoded);
        }
      }
    } catch (_) {
      // Optional enrichment
    } finally {
      if (_client == null) {
        httpClient.close();
      }
    }

    if (webCode != null) {
      final matchesApi = apiMeta != null && apiMeta.versionCode == webCode;
      return AppUpdateInfo(
        versionCode: webCode,
        versionName: webName ?? '1.0.0',
        mandatory: matchesApi ? apiMeta.mandatory : false,
        releaseNotes: matchesApi
            ? apiMeta.releaseNotes
            : 'A newer version of Crackers ERP Web is ready. Reload to apply the latest features and fixes.',
        downloadAvailable: true,
        downloadUrl: '/?v=$webCode',
      );
    }

    if (apiMeta != null) {
      return AppUpdateInfo(
        versionCode: apiMeta.versionCode,
        versionName: apiMeta.versionName,
        mandatory: apiMeta.mandatory,
        releaseNotes: apiMeta.releaseNotes,
        downloadAvailable: true,
        downloadUrl: '/?v=${apiMeta.versionCode}',
      );
    }

    return null;
  }

  @override
  Future<void> applyWebUpdate() async {
    // 1. Unregister Flutter Service Workers so the next load fetches fresh JS.
    try {
      final nav = _jsNavigator;
      if (nav != null && nav.hasProperty('serviceWorker'.toJS).toDart) {
        final sw = nav.getProperty('serviceWorker'.toJS);
        if (sw != null && sw.isA<JSObject>()) {
          final swObj = sw as JSObject;
          if (swObj.hasProperty('getRegistrations'.toJS).toDart) {
            final regsPromise =
                swObj.callMethod<JSPromise<JSArray<JSAny?>>>('getRegistrations'.toJS);
            final regs = await regsPromise.toDart;
            final list = regs.toDart;
            for (final reg in list) {
              if (reg != null && reg.isA<JSObject>()) {
                final unreg =
                    (reg as JSObject).callMethod<JSPromise<JSAny?>>('unregister'.toJS);
                await unreg.toDart;
              }
            }
          }
        }
      }
    } catch (_) {
      // Best-effort service worker cleanup
    }

    // 2. Clear Cache Storage entries.
    try {
      if (_jsWindow.hasProperty('caches'.toJS).toDart) {
        final caches = _jsWindow.getProperty('caches'.toJS);
        if (caches != null && caches.isA<JSObject>()) {
          final cachesObj = caches as JSObject;
          final keysPromise =
              cachesObj.callMethod<JSPromise<JSArray<JSString>>>('keys'.toJS);
          final keys = await keysPromise.toDart;
          for (final key in keys.toDart) {
            final del =
                cachesObj.callMethod<JSPromise<JSAny?>>('delete'.toJS, key);
            await del.toDart;
          }
        }
      }
    } catch (_) {
      // Best-effort Cache API cleanup
    }

    // 3. Reload current page cleanly.
    try {
      final loc = _jsWindow.getProperty('location'.toJS);
      if (loc != null && loc.isA<JSObject>()) {
        (loc as JSObject).callMethod<JSAny?>('reload'.toJS);
      }
    } catch (_) {}
  }

  @override
  Future<String> downloadApk(
    String downloadUrl,
    String fileName, {
    required void Function(AppUpdateDownloadProgress progress) onProgress,
  }) {
    throw UnsupportedError('Web updates reload the browser directly.');
  }

  @override
  Future<ApkInstallResult> installApk(String filePath) {
    throw UnsupportedError('Web updates reload the browser directly.');
  }
}

